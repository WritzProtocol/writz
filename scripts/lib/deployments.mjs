// Reads contracts/deployments/testnet.md, the record of every Writz testnet
// deployment, and returns the current network values. Everything that needs a
// contract ID in code (the @writz/sdk network preset, contracts/deployments/
// testnet.json) is generated from this, never copied by hand.
//
// The record is newest first. A contract's current ID is the first
// "**Contract ID**" row in a section whose heading names the contract and is
// not marked superseded, so a redeploy only has to add its section on top.

import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

export const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
export const testnetMdPath = path.join(repoRoot, "contracts/deployments/testnet.md");

const CONTRACTS = ["bitcoin-spv", "writz-lend", "commitment-tree", "zk-verifier"];
const ID = "C[A-Z2-7]{55}";

function names(heading, contract) {
  return new RegExp(`(^|[^a-z-])${contract}([^a-z-]|$)`).test(heading);
}

function field(md, label, re) {
  const m = md.match(re);
  if (!m) throw new Error(`testnet.md: could not find ${label}`);
  return m[1];
}

/** Parses the deployment record. Throws if a value is missing. */
export function parseTestnetDeployments(md = readFileSync(testnetMdPath, "utf8")) {
  const current = {};
  /** Every ID ever recorded for each contract, current or not. */
  const history = Object.fromEntries(CONTRACTS.map((c) => [c, new Set()]));
  let h2 = "";
  let h3 = "";

  for (const line of md.split("\n")) {
    const heading = line.match(/^(#{2,3})\s+(.*\S)\s*$/);
    if (heading) {
      if (heading[1] === "##") {
        h2 = heading[2];
        h3 = "";
      } else {
        h3 = heading[2];
      }
      continue;
    }
    const section = h3 || h2;
    const superseded = /superseded/i.test(`${h2} ${h3}`);

    const idRow = line.match(new RegExp(`\\*\\*Contract ID\\*\\*\\s*\\|\\s*\`(${ID})\``));
    if (idRow) {
      for (const c of CONTRACTS) {
        if (!names(section, c)) continue;
        history[c].add(idRow[1]);
        if (!superseded && !current[c]) current[c] = idRow[1];
      }
    }
    // Summary tables: | `writz-lend` | `C...` | ...
    const tableRow = line.match(new RegExp(`^\\|\\s*\`([a-z-]+)\`\\s*\\|\\s*\`(${ID})\``));
    if (tableRow && history[tableRow[1]]) history[tableRow[1]].add(tableRow[2]);
  }

  for (const c of ["bitcoin-spv", "writz-lend"]) {
    if (!current[c]) throw new Error(`testnet.md: no current Contract ID for ${c}`);
  }

  return {
    network: "testnet",
    networkPassphrase: field(md, "network passphrase", /\*\*Network:\*\*[^`]*`([^`]+)`/),
    rpcUrl: field(md, "Soroban RPC", /\*\*Soroban RPC:\*\*\s*`([^`]+)`/),
    relayerUrl: field(md, "relayer", /\*\*Relayer:\*\*\s*`([^`]+)`/),
    bitcoinNetwork: "signet",
    spvCheckpointHeight: Number(
      field(md, "bitcoin-spv checkpoint height", /\|\s*Checkpoint\s*\|\s*signet block ([\d,]+)/).replace(/,/g, ""),
    ),
    contracts: {
      bitcoinSpv: current["bitcoin-spv"],
      writzLend: current["writz-lend"],
      usdc: field(md, "usdc_token", new RegExp(`\`usdc_token\`\\s*\\|\\s*\`(${ID})\``)),
      oracle: field(md, "oracle", new RegExp(`\`oracle\`\\s*\\|\\s*\`(${ID})\``)),
    },
    history: Object.fromEntries(Object.entries(history).map(([k, v]) => [k, [...v]])),
  };
}

/** The generated files, keyed by repo-relative path. */
export function generatedFiles(d = parseTestnetDeployments()) {
  const { history: _history, ...preset } = d;
  const json = JSON.stringify(preset, null, 2) + "\n";
  const ts =
    "// Generated by scripts/sync-deployments.mjs from contracts/deployments/testnet.md.\n" +
    "// Do not edit: change the deployment record and run `node scripts/sync-deployments.mjs`.\n\n" +
    'import type { NetworkPreset } from "./types.js";\n\n' +
    `export const testnet: NetworkPreset = ${JSON.stringify(preset, null, 2)} as const;\n`;
  return {
    "contracts/deployments/testnet.json": json,
    "packages/sdk/src/networks.generated.ts": ts,
  };
}
